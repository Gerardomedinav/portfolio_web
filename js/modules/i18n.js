const availableLangs = ['en', 'es'];
const defaultLang = 'es';

export function getLang() {
  const saved = localStorage.getItem('lang');
  return availableLangs.includes(saved) ? saved : defaultLang;
}

export function updateNavTexts(lang) {
  const navHome = document.querySelector('a[href="#home"]');
  const navAbout = document.querySelector('a[href="#about"]');
  const navProjects = document.querySelector('a[href="#projects"]');
  const navSkills = document.querySelector('a[href="#skills"]');
  const navContact = document.querySelector('a[href="#contact"]');

  if (navHome) navHome.textContent = texts[lang].home;
  if (navAbout) navAbout.textContent = texts[lang].about;
  if (navProjects) navProjects.textContent = texts[lang].projects;
  if (navSkills) navSkills.textContent = texts[lang].skills;
  if (navContact) navContact.textContent = texts[lang].contact;

  const labelName = document.querySelector('label[for="name"]');
  const labelEmail = document.querySelector('label[for="email"]');
  const labelMessage = document.querySelector('label[for="message"]');
  const btnSend = document.querySelector('button[type="submit"]');
  const footerCopy = document.querySelector('.footer__copy');

  if (labelName) labelName.textContent = texts[lang].contactName;
  if (labelEmail) labelEmail.textContent = texts[lang].contactEmail;
  if (labelMessage) labelMessage.textContent = texts[lang].contactMessage;
  if (btnSend) btnSend.textContent = texts[lang].contactSend;
  if (footerCopy) footerCopy.textContent = texts[lang].footerCopy;
}

export function translatePage(lang) {
  if (!availableLangs.includes(lang)) return;
  document.documentElement.lang = lang;

  const elements = document.querySelectorAll('[data-i18n]');
  elements.forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang] && translations[lang][key]) {
      el.innerHTML = translations[lang][key];
    }
  });

  const altElements = document.querySelectorAll('[data-i18n-alt]');
  altElements.forEach(el => {
    const key = el.getAttribute('data-i18n-alt');
    if (translations[lang] && translations[lang][key]) {
      el.alt = translations[lang][key];
    }
  });

  const ariaElements = document.querySelectorAll('[data-i18n-aria]');
  ariaElements.forEach(el => {
    const key = el.getAttribute('data-i18n-aria');
    if (translations[lang] && translations[lang][key]) {
      el.setAttribute('aria-label', translations[lang][key]);
    }
  });
}

/**
 * Previsualización del CV en PDF sin descarga instantánea
 */
export function updateResumeLink(lang) {
  const resumeLink = document.querySelector('a[data-i18n="resume"]');
  const botCvLink = document.getElementById('bot-cta-cv');

  if (resumeLink) {
    if (lang === 'es') {
      resumeLink.href = './assets/CV_Gerardo_Medina_Villalba_espanol.pdf';
      resumeLink.setAttribute('aria-label', 'Previsualizar Currículum Vitae de Gerardo Medina (PDF en nueva pestaña)');
    } else {
      resumeLink.href = './assets/CV_Gerardo_Medina_Villalba_EN.pdf';
      resumeLink.setAttribute('aria-label', 'Preview Gerardo Medina\'s Resume (PDF in new tab)');
    }
    resumeLink.target = '_blank';
    resumeLink.rel = 'noopener noreferrer';
    // Remover atributo download para permitir previsualización antes de descargar
    resumeLink.removeAttribute('download');
  }

  if (botCvLink) {
    if (lang === 'es') {
      botCvLink.href = './assets/CV_Gerardo_Medina_Villalba_espanol.pdf';
    } else {
      botCvLink.href = './assets/CV_Gerardo_Medina_Villalba_EN.pdf';
    }
  }
}

export function setLanguage(lang) {
  if (!availableLangs.includes(lang)) return;
  localStorage.setItem('lang', lang);

  updateNavTexts(lang);
  translatePage(lang);
  updateResumeLink(lang);

  // Disparar evento personalizado para actualizar dinámicamente proyectos y habilidades
  document.dispatchEvent(new CustomEvent('languageChange', { detail: { lang } }));
}

export function initI18n() {
  const currentLang = getLang();

  const languageSelectors = [
    document.getElementById('language-select-header'),
    document.getElementById('language-select-widget')
  ].filter(Boolean);

  languageSelectors.forEach(selector => {
    selector.value = currentLang;
    selector.addEventListener('change', (e) => {
      const newLang = e.target.value;
      if (availableLangs.includes(newLang)) {
        // Sincronizar el otro selector
        languageSelectors.forEach(s => {
          if (s !== e.target) s.value = newLang;
        });
        setLanguage(newLang);
      }
    });
  });

  setLanguage(currentLang);
}
